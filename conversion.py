def centimetrosApulgadas(cm):
    pulgadas = cm / 2.54
    return pulgadas

def pulgadasAcentimetros(pulgadas):
    cm = pulgadas * 2.54
    return cm

def piesAmetros(pies):
    metros = pies * 0.3048
    return metros

def metrosApies(metros):
    pies = metros / 0.3048
    return pies

def millasAkilometros(millas):
    km = millas * 1.60934
    return km

def kilometrosAmillas(km):
    millas = km / 1.60934
    return millas
